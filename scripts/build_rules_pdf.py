"""Build a readable PDF and import sidecar from a Wahapedia rules snapshot."""
import argparse
import hashlib
import json
from pathlib import Path
from xml.sax.saxutils import escape

import pymupdf
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import SimpleDocTemplate, Paragraph, PageBreak, Spacer


def build(snapshot, output):
    data = json.loads(snapshot.read_text(encoding='utf-8'))
    output.parent.mkdir(parents=True, exist_ok=True)
    fontdir = Path('C:/Windows/Fonts')
    pdfmetrics.registerFont(TTFont('Rules', str(fontdir/'arial.ttf')))
    pdfmetrics.registerFont(TTFont('RulesBold', str(fontdir/'arialbd.ttf')))
    styles = getSampleStyleSheet()
    body = ParagraphStyle('RuleBody', fontName='Rules', fontSize=10, leading=14, spaceAfter=7)
    title = ParagraphStyle('RuleTitle', parent=body, fontName='RulesBold', fontSize=19, leading=24, spaceAfter=14)
    small = ParagraphStyle('Source', parent=body, fontSize=8, leading=11, textColor=colors.HexColor('#40546a'))
    starts = []

    class Document(SimpleDocTemplate):
        def afterFlowable(self, flowable):
            if hasattr(flowable, 'rule_index'):
                starts.append((flowable.rule_index, self.page))

    def clean(text):
        for char in '\u2010\u2011\u2012\u2013\u2014':
            text = text.replace(char, '-')
        return text

    def footer(canvas, doc):
        canvas.setFont('Rules', 8)
        canvas.setFillColor(colors.HexColor('#526273'))
        canvas.drawString(44, 26, 'Wahapedia | 11th edition | Secondary-source snapshot')
        canvas.drawRightString(A4[0]-44, 26, str(doc.page))

    story = [Paragraph('Wahapedia Core Rules', title),
             Paragraph('Warhammer 40,000 - 11th edition', body), Spacer(1, 14),
             Paragraph('Retrieved: '+escape(data['retrieved_at']), body),
             Paragraph('A generated reading copy of a secondary rules compilation. This is not an official Games Workshop publication. The retrieval date is not the effective date of an amendment.', body),
             Paragraph('Original source: <link href="'+escape(data['source_url'])+'">'+escape(data['source_url'])+'</link>', small),
             Paragraph('HTML snapshot SHA-256: '+data['sha256'], small),
             Paragraph('Rules are kept as numbered entries, with FAQ text and source links. PDF page numbers belong to this generated copy. Illustrations are referenced by URL rather than reproduced.', body)]
    for index, rule in enumerate(data['sections']):
        story.append(PageBreak())
        heading = Paragraph(escape(clean(rule['rule_number']+' - '+rule['title'])), title)
        heading.rule_index = index
        story.append(heading)
        story.append(Paragraph('<link href="'+escape(rule['source_url'])+'">View this rule on Wahapedia</link>', small))
        for block in rule['body'].split('\n\n'):
            if block.strip():
                story.append(Paragraph(escape(clean(block)).replace('\n', '<br/>'), body))
    doc = Document(str(output), pagesize=A4, leftMargin=44, rightMargin=44,
                   topMargin=42, bottomMargin=44, title='Wahapedia Core Rules - snapshot', author='Wahapedia; generated by Lexi importer')
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    sections = []
    with pymupdf.open(output) as pdf:
        pages = [{'page': i+1, 'printed_label': str(i+1), 'text': p.get_text(),
                  'extraction_metadata': {'source_kind': 'secondary_compilation', 'snapshot_sha256': data['sha256']}}
                 for i,p in enumerate(pdf)]
        for position, (index, start) in enumerate(starts):
            rule = data['sections'][index]
            end = starts[position+1][1]-1 if position+1<len(starts) else len(pdf)
            sections.append({'heading_path': rule['rule_number']+' - '+rule['title'],
                'page_start': start, 'page_end': end,
                'spans': [{'page': start, 'printed_label': str(start),
                           'text': rule['body']+'\n\nWahapedia source: '+rule['source_url']} ]})
        assert len(sections)==len(data['sections'])
    sidecar = {'pdf_sha256': hashlib.sha256(output.read_bytes()).hexdigest(),
               'provenance': {k:v for k,v in data.items() if k!='sections'},
               'pages': pages, 'sections': sections}
    output.with_suffix('.json').write_text(json.dumps(sidecar,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({'pdf':str(output),'pages':len(pages),'sections':len(sections)}))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('snapshot',type=Path)
    p.add_argument('--output',type=Path,default=Path('output/pdf/wahapedia-core-rules.pdf'))
    a=p.parse_args()
    build(a.snapshot,a.output)
